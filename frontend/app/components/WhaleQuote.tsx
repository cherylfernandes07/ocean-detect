/**
 * WhaleQuote.tsx
 *
 * Displays a single imagined quote from an orca, styled like a pull-quote.
 *
 * This is the creative heart of the app — the LangChain workflow generates
 * a short monologue in the voice of a named orca, and this component gives
 * it visual weight: big quotation marks, the orca's name, call type tag.
 *
 * Accessibility:
 *   - Uses <blockquote> — semantically correct for a quotation
 *   - <cite> for the orca's name (correct HTML for a source attribution)
 *   - aria-label clarifies this is an imagined/creative quote, not a fact
 */

import React from "react";

export interface WhaleQuoteProps {
  /** The imagined monologue text generated by the LLM */
  quote: string;
  /** Orca's name, e.g. "Tahlequah" */
  orcaName: string;
  /** Ford-Osborne call type, e.g. "S19" */
  callType?: string;
  /** ISO timestamp of when this quote was generated */
  timestamp?: string;
  /** Whether this quote is being generated right now */
  isGenerating?: boolean;
}

export default function WhaleQuote({
  quote,
  orcaName,
  callType,
  timestamp,
  isGenerating = false,
}: WhaleQuoteProps) {
  return (
    <figure
      className="rounded-2xl border border-cyan-800/40 bg-gradient-to-br from-slate-900 to-cyan-950 p-6 shadow-lg"
      aria-label={`Imagined quote from ${orcaName} — creative interpretation, not a real statement`}
    >
      {/* Giant decorative quotation mark — purely visual, hidden from screen readers */}
      {/* Orca illustration — SVG so it's crisp at any size */}
      <div className="flex items-center gap-4 mb-4">
        <svg
          viewBox="0 0 120 60"
          className="w-24 h-12 text-cyan-600"
          fill="currentColor"
          aria-hidden="true"
        >
          {/* Body */}
          <ellipse cx="55" cy="32" rx="42" ry="16" />
          {/* Dorsal fin */}
          <path d="M60 32 Q65 8 75 16 Q70 24 60 32Z" />
          {/* Tail flukes */}
          <path d="M13 32 Q4 22 2 14 Q10 20 13 28 Q16 20 24 14 Q22 22 13 32Z" />
          {/* White eye patch */}
          <ellipse cx="85" cy="27" rx="6" ry="4" fill="white" opacity="0.9" />
          {/* White saddle patch */}
          <ellipse cx="65" cy="24" rx="10" ry="5" fill="white" opacity="0.15" />
        </svg>

        <div>
          <p className="text-xs font-mono text-cyan-500 uppercase tracking-widest">J-Pod · Southern Resident</p>
          <p className="text-xs text-slate-500 mt-0.5">Puget Sound, Pacific Northwest</p>
        </div>
      </div>      
      {/* The quote body */}
      <blockquote className="mt-2 mb-4">
        {isGenerating ? (
          /* Loading state: animated shimmer lines while the LLM streams */
          <div className="space-y-2" aria-label="Generating whale voice…">
            <div className="h-4 w-full animate-pulse rounded bg-cyan-800/30" />
            <div className="h-4 w-5/6 animate-pulse rounded bg-cyan-800/30" />
            <div className="h-4 w-4/6 animate-pulse rounded bg-cyan-800/30" />
          </div>
        ) : (
          <p className="text-lg leading-relaxed text-cyan-100 italic">
            {quote}
          </p>
        )}
      </blockquote>

      {/* Attribution row: name + call type tag + timestamp */}
      <figcaption className="flex flex-wrap items-center gap-3 text-sm">
        <cite className="not-italic font-semibold text-cyan-300">
          — {orcaName}
        </cite>

        {callType && (
          <span className="rounded-full bg-cyan-800/40 px-2.5 py-0.5 text-xs font-mono text-cyan-400 border border-cyan-700/40">
            {callType}
          </span>
        )}

        {timestamp && (
          <time
            dateTime={timestamp}
            className="ml-auto text-slate-500 text-xs"
          >
            {timestamp}
          </time>
        )}
      </figcaption>

      {/* Disclaimer — small, clear, important for scientific integrity */}
      <p className="mt-3 text-xs text-slate-500 italic">
        * Imagined voice — creative interpretation of detected call patterns
      </p>
    </figure>
  );
}
